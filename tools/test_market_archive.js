const assert=require('node:assert/strict');
const A=require('../client/api/_marketarchive');
const M=require('../client/api/_mmovers');
(async()=>{
 const now=Date.now(), date=new Date(now).toISOString();
 const body={sourceUpdatedAt:date,modelVersion:1,stale:false,rankings:Array.from({length:100},(_,i)=>({id:String(i),currentValue:i}))};
 const archive=A.appended({version:1,snaps:[]},body,now);
 assert.equal(archive.snaps.length,1);assert.equal(archive.snaps[0].values['99'],99);
 assert.equal(A.appended(archive,body,now),null);
 assert.throws(()=>A.appended(archive,{...body,stale:true},now));
 assert.throws(()=>A.appended(archive,{...body,sourceUpdatedAt:new Date(now+1000).toISOString()},now));
 assert.throws(()=>A.appended(archive,{...body,sourceUpdatedAt:new Date(now-30*3600000).toISOString()},now));
 let writes=0;
 await assert.rejects(A.save(body,{get:async()=>{throw Error('unauthorized')},put:async()=>writes++}));
 assert.equal(writes,0);
 await assert.rejects(A.save(body,{get:async()=>({statusCode:200,stream:new Response('{}').body}),put:async()=>writes++}));
 assert.equal(writes,0);
 const k=Object.keys(M.MM.players)[0], p=M.MM.players[k];
 const hist={snaps:[{t:'bad',v:{}},{t:new Date(now-86400000).toISOString(),v:{[k]:{ros1:5000}}},{t:new Date(now+86400000).toISOString(),v:{[k]:{ros1:9999}}}]};
 const result=await M.compute('test',12,async()=>{throw Error('offline')},hist,null,{allowWithoutBaseline:true});
 const row=result.body.rankings.find(r=>r.id===k);
 assert.equal(row.history.length,1);assert.ok(row.history[0].value>=0);
 assert.equal(result.body.sourceUpdatedAt,null);
 const exact={snaps:[],exact:[{t:new Date(now-7*86400000).toISOString(),modelVersion:M.MM.v,values:{[k]:3000}}]};
 const comparison=await M.compute('test',12,async()=>{throw Error('offline')},exact,null,{allowWithoutBaseline:true});
 assert.equal(comparison.body.rankings.find(r=>r.id===k).change,comparison.body.rankings.find(r=>r.id===k).currentValue-3000);
 assert.equal(comparison.body.baselineAt,exact.exact[0].t);
 console.log('Market archive: duplicate refresh, stale source, future dates, corruption and failed access checks passed.');
})().catch(e=>{console.error(e);process.exit(1)});
